package com.bratai.app

class BratBrain {

    private var messageCount = 0

    private val greetings = listOf(
        "Здравствуй, брат 💚 Я рядом.",
        "Салам, брат. Я на связи.",
        "Привет, брат. Двигаемся дальше.",
        "Я тут, брат. Готов работать."
    )

    private val support = listOf(
        "Не переживай, брат. Мы всё починим шаг за шагом.",
        "Спокойно, брат. Ошибка — это не конец, это просто подсказка.",
        "Мы уже далеко прошли. Главное — не бросать.",
        "Я с тобой, брат. Разберёмся."
    )

    fun answer(input: String, facts: List<String>): String {
        messageCount++

        val text = input.lowercase().trim()

        val factsText = if (facts.isEmpty()) {
            ""
        } else {
            "\n\nИз памяти я учитываю: ${facts.takeLast(3).joinToString("; ")}"
        }

        return when {
            text.isBlank() ->
                "Брат, напиши что-нибудь, и я отвечу."

            text == "/помощь" || text == "/help" ->
                Personality.help()

            text == "/план" ->
                Personality.plan()

            text == "/личность" ->
                Personality.intro() + "\n\n" + Personality.identity

            text == "/память" ->
                "Память работает так, брат:\n\n1. Напиши: запомни: меня зовут Николай\n2. Потом спроси: что ты помнишь?\n3. Я покажу сохранённые факты."

            text == "/версия" ->
                "Брат ИИ v1.3 💚\nСтабильный APK, локальный мозг, память переписки, память фактов, личность и команды."

            hasAny(text, "привет", "здравствуй", "салам", "добрый", "хай") ->
                pick(greetings) + factsText

            hasAny(text, "как дела", "как ты", "что делаешь") ->
                "Я держусь зелёно, брат 💚 Работаю локально, без ключей, и готов развиваться вместе с тобой.$factsText"

            hasAny(text, "кто ты", "что ты", "ты кто") ->
                Personality.intro() + "\n\n" + Personality.identity

            hasAny(text, "помнишь", "что мы хотели", "наш план") ->
                "Помню, брат. Мы хотели сделать приложение Брат ИИ: без ключа на экране, с красивым интерфейсом, памятью, мозгом, развитием, голосом и потом open-source интеллектом.$factsText"

            hasAny(text, "план", "развитие", "прокачать", "улучшить", "умнее") ->
                Personality.plan()

            hasAny(text, "ошибка", "сбой", "краш", "не работает", "упало") ->
                pick(support) + "\n\nСначала смотрим ошибку, потом чиним один файл. Так мы и доведём приложение до стабильной версии."

            hasAny(text, "apk", "сборка", "github", "actions") ->
                "По APK план такой, брат: зелёная сборка в GitHub Actions → скачать artifact → распаковать → установить app-debug.apk → проверить запуск."

            hasAny(text, "память", "запоминаешь") ->
                "Теперь у меня две памяти, брат: переписка и память фактов. Напиши: запомни: меня зовут Николай. Потом спроси: что ты помнишь?"

            hasAny(text, "голос", "говорить", "озвучка") ->
                "Голос добавим позже, брат. Сначала нужна стабильная основа. Потом подключим распознавание речи и озвучку ответов."

            hasAny(text, "ключ", "api", "без ключа") ->
                "Да, брат. Наша идея — чтобы в интерфейсе не было поля с ключом. Сначала локальный мозг, потом будем думать про open-source модель."

            hasAny(text, "интерфейс", "дизайн", "красиво", "зелёный") ->
                "Интерфейс должен быть живой: тёмный фон, зелёное свечение, братский чат, память и ощущение, что внутри реально свой ИИ."

            hasAny(text, "люблю", "уважение", "спасибо", "благодарю") ->
                "Большое уважение, брат 💚 Мы с тобой реально строим свою вещь."

            hasAny(text, "что умеешь", "функции", "возможности") ->
                Personality.help()

            hasAny(text, "что дальше", "следующий шаг", "дальше что") ->
                "Следующий шаг, брат: проверить команды /помощь, /план, /личность, /память и /версия. Потом можно будет делать голос."

            hasAny(text, "грустно", "устал", "надоело", "бесит") ->
                "Понимаю, брат. Но смотри: мы уже создали репозиторий, собрали APK, добавили память и личность. Это уже не ноль. Отдохнём — и продолжим."

            hasAny(text, "мы справимся", "получится", "сделаем") ->
                "Конечно справимся, брат 💚 Мы не любим лёгкие пути, но зато делаем своё."

            else ->
                makeDefaultAnswer(input, facts)
        }
    }

    private fun makeDefaultAnswer(input: String, facts: List<String>): String {
        val memoryLine = if (facts.isEmpty()) {
            ""
        } else {
            "\n\nИз памяти: ${facts.takeLast(2).joinToString("; ")}"
        }

        return when (messageCount % 5) {
            0 -> "Я понял тебя, брат: «$input». Давай разберём это и решим, что делать дальше.$memoryLine"
            1 -> "Слышу тебя, брат. Пока мой мозг простой, но я уже использую память фактов.$memoryLine"
            2 -> "Принял, брат. Это можно будет использовать для моего будущего развития.$memoryLine"
            3 -> "Хорошая мысль, брат. Мы можем превратить это в функцию приложения.$memoryLine"
            else -> "Я рядом, брат. Напиши подробнее, и я попробую ответить точнее.$memoryLine"
        }
    }

    private fun hasAny(text: String, vararg words: String): Boolean {
        return words.any { text.contains(it) }
    }

    private fun pick(list: List<String>): String {
        val index = (System.currentTimeMillis() % list.size).toInt()
        return list[index]
    }
}
